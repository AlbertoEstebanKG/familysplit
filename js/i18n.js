const DICTS = { ru: RU, en: EN, ky: KY };
let lang = 'ru';

export function setLang(l) { lang = LANGS.includes(l) ? l : 'ru'; }
export function getLang() { return lang; }
/** Локаль для чисел и дат. */
export function locale() { return { ru: 'ru-RU', en: 'en-GB', ky: 'ky-KG' }[lang]; }

function fill(s, params) {
  return params ? s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? '')) : s;
}

export function t(key, params) {
  const s = DICTS[lang][key] ?? RU[key] ?? key;
  return fill(s, params);
}

export function plural(key, n) {
  const forms = PLURALS[lang][key] || PLURALS.ru[key];
  let cat = 'other';
  try { cat = new Intl.PluralRules(locale()).select(n); } catch {}
  const s = forms[cat] ?? forms.other;
  return fill(s, { n: new Intl.NumberFormat(locale(), { maximumFractionDigits: 2 }).format(n) });
}

